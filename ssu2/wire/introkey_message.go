// Intro-key protected out-of-session messages.
//
// ssu2.rst §"Header Encryption Keys" defines a family of messages whose header
// AND payload keys are simply the receiver's 32-byte introduction key:
//
//	Token Request  k = aik   k_header_1 = aik  k_header_2 = aik
//	Retry          k = bik   k_header_1 = bik  k_header_2 = bik
//	Peer Test 5,7  k = aik   k_header_1 = aik  k_header_2 = aik
//	Peer Test 6    k = cik   k_header_1 = cik  k_header_2 = cik
//	Hole Punch     k = aik   k_header_1 = aik  k_header_2 = aik
//
// with, per each message's KDF section:
//
//	n  = 4 byte packet number from header (random per message)
//	ad = 32 byte header, BEFORE header encryption
//
// so construction order is fixed: build the cleartext long header, AEAD-seal the
// payload against it, serialize, and only then apply header protection.
//
// These messages are NOT part of the Noise handshake and carry no ephemeral
// key; they must still satisfy the universal SSU2 framing rules — a 32-byte
// long header, an AEAD-sealed payload, a 16-byte Poly1305 tag, and a total
// datagram of at least MinPacketSize (40) bytes. A cleartext 16-byte header
// with an unencrypted payload is not a valid SSU2 message of any type.
//
// Retry already followed exactly this construction (see retry_aead.go and
// server.sendRetry); this file generalizes it so Peer Test and Hole Punch —
// and any future intro-key message — share one auditable builder.

// IntroKeyMessageSpec describes one intro-key protected out-of-session message.
type IntroKeyMessageSpec struct {
	// MessageType is the wire type byte (7 PeerTest, 9 Retry, 10 TokenRequest,
	// 11 HolePunch).
	MessageType uint8

	// DestConnID is header bytes 0-7.
	DestConnID uint64

	// SourceConnID is header bytes 16-23.
	SourceConnID uint64

	// Token is header bytes 24-31. Per-message rules differ: zero for Token
	// Request, the issued token for Retry, random (ignored by the receiver)
	// for Hole Punch, zero for Peer Test.
	Token []byte

	// Blocks is the plaintext payload block list. PadPayloadToMin is applied
	// if the serialized payload is below the 8-byte floor.
	Blocks []*SSU2Block

	// NetworkID is header byte 14. Zero selects the main-network value
	// (MainNetworkID = 2); test networks pass their own value so that peers on
	// another network reject the message, per proposal 147.
	NetworkID uint8
}

// BuildIntroKeyMessage constructs and returns a complete, wire-ready intro-key
// protected SSU2 message.
//
// The returned datagram is:
//
//	header[0:16]   XOR-masked with ChaCha20 masks derived from the packet tail
//	header[16:32]  ChaCha20-encrypted with k_header_2 (= receiver intro key)
//	payload        ChaCha20-Poly1305(k=intro key, n=packet number, ad=cleartext header)
//	MAC[16]        Poly1305 tag
//
// Parameters:
//   - introKey: the RECEIVER's 32-byte introduction key
//   - spec:     message description
//
// Returns the protected datagram, the packet number used (which is also the
// AEAD nonce), and any error. Construction fails closed: a wrong-length intro
// key, a missing token field, or a payload that cannot be sealed aborts before
// anything is written, so no partially-protected message can reach the wire.
func BuildIntroKeyMessage(introKey []byte, spec *IntroKeyMessageSpec) (packet []byte, packetNumber uint32, err error) {
	if spec == nil {
		return nil, 0, oops.Errorf("intro-key message spec is nil")
	}
	if len(introKey) != HeaderKeySize {
		return nil, 0, oops.
			Code("INVALID_INTRO_KEY").
			In("ssu2").
			With("key_len", len(introKey)).
			Errorf("intro-key message requires a %d-byte receiver intro key", HeaderKeySize)
	}

	// The packet number doubles as the AEAD nonce and is random per message
	// ("Packet Number :: Random number generated by Alice or Charlie").
	pn, err := cryptorand.RandInRange(1, int64(MaxPacketNumber))
	if err != nil {
		return nil, 0, oops.Wrapf(err, "failed to generate packet number")
	}
	packetNumber = uint32(pn)

	header := buildIntroKeyHeader(spec, packetNumber)

	payload, err := SerializeBlocks(spec.Blocks)
	if err != nil {
		return nil, 0, oops.Wrapf(err, "failed to serialize intro-key message payload blocks")
	}
	// ssu2.rst: "The minimum payload size is 8 bytes ... If the requirement is
	// not met, a Padding block must be included." Floor applies to plaintext.
	if len(payload) < MinPayloadSize {
		payload, err = PadPayloadToMin(payload)
		if err != nil {
			return nil, 0, oops.Wrapf(err, "failed to pad intro-key message payload")
		}
	}

	ciphertext, mac, err := EncryptIntroKeyAEAD(introKey, header, payload, packetNumber)
	if err != nil {
		return nil, 0, oops.Wrapf(err, "failed to AEAD-seal intro-key message payload")
	}

	pkt := NewSSU2Packet(spec.MessageType, packetNumber)
	pkt.Header = header
	pkt.Payload = ciphertext
	pkt.MAC = mac

	data, err := pkt.Serialize()
	if err != nil {
		return nil, 0, oops.Wrapf(err, "failed to serialize intro-key message")
	}

	// Header protection last: the AEAD committed to the cleartext header.
	// The header type is derived from the message type rather than supplied by
	// the caller, so a spec whose HeaderType disagrees with its MessageType is
	// structurally impossible.
	protector, err := NewHeaderProtectorFromIntroKey(introKey, introKeyHeaderTypeFor(spec.MessageType))
	if err != nil {
		return nil, 0, oops.Wrapf(err, "failed to build header protector")
	}
	if err := protector.EncryptHeader(data); err != nil {
		return nil, 0, oops.Wrapf(err, "failed to apply header protection")
	}

	flog("BuildIntroKeyMessage", logger.Fields{
		"messageType": spec.MessageType,
		"packetNum":   packetNumber,
		"size":        len(data),
	}).Debug("built intro-key protected message")

	return data, packetNumber, nil
}

// introKeyHeaderTypeFor maps an intro-key message type to its
// header-protection type. Every message in this family uses the receiver's
// intro key for both k_header_1 and k_header_2 and carries a 32-byte long
// header with no ephemeral key, so the mapping only has to pick the right
// long-header case.
func introKeyHeaderTypeFor(messageType uint8) HeaderType {
	switch messageType {
	case MessageTypeRetry:
		return HeaderTypeRetry
	case MessageTypeTokenRequest:
		return HeaderTypeTokenRequest
	case MessageTypePeerTest:
		return HeaderTypePeerTest
	case MessageTypeHolePunch:
		return HeaderTypeHolePunch
	default:
		// The intro-key family is closed; anything else is a caller error.
		// SessionRequest/Created are not intro-key AEAD messages and Data /
		// SessionConfirmed use KDF-derived keys.
		return HeaderTypeRetry
	}
}

// buildIntroKeyHeader lays out the 32-byte cleartext long header for an
// intro-key message. Field order per ssu2.rst §"Header" and each message's
// "Unencrypted data" table:
//
//	0-7   destination connection ID
//	8-11  packet number (big endian; also the AEAD nonce)
//	12    message type
//	13    protocol version (2)
//	14    network ID
//	15    flag (unused, 0)
//	16-23 source connection ID
//	24-31 token
func buildIntroKeyHeader(spec *IntroKeyMessageSpec, packetNumber uint32) []byte {
	header := make([]byte, LongHeaderSize)
	binary.BigEndian.PutUint64(header[0:8], spec.DestConnID)
	binary.BigEndian.PutUint32(header[8:12], packetNumber)
	header[12] = spec.MessageType
	header[13] = SSU2ProtocolVersion
	header[14] = spec.networkID()
	header[15] = 0 // flag: unused, set to 0 for future compatibility
	binary.BigEndian.PutUint64(header[16:24], spec.SourceConnID)
	if len(spec.Token) > 0 {
		copy(header[24:32], spec.Token)
	}
	return header
}

// networkID returns the configured network ID, defaulting to the main network
// when unset so that struct-literal specs stay compliant without extra wiring.
func (spec *IntroKeyMessageSpec) networkID() uint8 {
	if spec.NetworkID == 0 {
		return MainNetworkID
	}
	return spec.NetworkID
}

// OpenIntroKeyMessage reverses BuildIntroKeyMessage: it removes header
// protection and opens the payload AEAD using the receiver's intro key.
//
// Parameters:
//   - introKey: our (the receiver's) 32-byte introduction key
//   - data: the received datagram (modified on a copy, not in place)
//
// Returns the deserialized packet (with a plaintext header and still-encrypted
// payload) and the decrypted payload blocks. Any failure — bad length, header
// that does not de-obfuscate to a coherent packet, or AEAD verification failure
// — returns an error, and callers must then drop the message without
// responding, per the spec's probing-resistance rules.
func OpenIntroKeyMessage(introKey []byte, data []byte) (*SSU2Packet, []*SSU2Block, error) {
	if len(introKey) != HeaderKeySize {
		return nil, nil, oops.Errorf("intro key must be %d bytes", HeaderKeySize)
	}

	decrypted := make([]byte, len(data))
	copy(decrypted, data)

	// Any long-header header type works: DecryptHeaderForPacket derives the
	// extension span from the de-masked type byte, not from the configured type.
	protector, err := NewHeaderProtectorFromIntroKey(introKey, HeaderTypeTokenRequest)
	if err != nil {
		return nil, nil, oops.Wrapf(err, "failed to build header protector")
	}
	if err := protector.DecryptHeader(decrypted); err != nil {
		return nil, nil, oops.Wrapf(err, "failed to de-obfuscate header")
	}

	pkt := &SSU2Packet{}
	if err := pkt.Deserialize(decrypted); err != nil {
		return nil, nil, oops.Wrapf(err, "failed to deserialize packet")
	}

	// The AEAD's associated data is the cleartext 32-byte header, which the
	// de-obfuscated bytes now are.
	plaintext, err := DecryptIntroKeyAEAD(introKey, pkt.Header[:LongHeaderSize], pkt.Payload, pkt.MAC, pkt.PacketNumber)
	if err != nil {
		return nil, nil, oops.Wrapf(err, "failed to open payload AEAD")
	}

	blocks, err := DeserializeBlocks(plaintext)
	if err != nil {
		return nil, nil, oops.Wrapf(err, "failed to deserialize payload blocks")
	}
	return pkt, blocks, nil
}

// NewDateTimeBlock builds the DateTime block (type 0, 4-byte big-endian Unix
// seconds) required at the head of the payload of Token Request, Peer Test and
// Hole Punch messages per their §"Payload" lists.
func NewDateTimeBlock() *SSU2Block {
	data := make([]byte, 4)
	binary.BigEndian.PutUint32(data, uint32(time.Now().Unix()))
	return NewSSU2Block(BlockTypeDateTime, data)
}

// NewAddressBlockForAddr builds the Address block (type 13) reporting an
// observed IP/port, required in Peer Test messages 6 and 7 and in Hole Punch.
// A nil address yields the all-zeros IPv4 form rather than an error, matching
// EncodeAddressBlock's treatment of an unknown address.
func NewAddressBlockForAddr(addr *net.UDPAddr) *SSU2Block {
	if addr == nil {
		return EncodeAddressBlock(net.IPv4zero, 0)
	}
	ip := addr.IP
	if ip == nil {
		ip = net.IPv4zero
	}
	return EncodeAddressBlock(ip, uint16(addr.Port))
}

// NonceConnectionIDs derives the deterministic connection-ID pair used by the
// out-of-session Peer Test (messages 5-7) and Hole Punch messages from the
// 4-byte test/relay nonce, per ssu2.rst §"Peer Test (Type 7)" and §"Hole Punch
// (Type 11)":
//
//	dest = ((nonce << 32) | nonce)
//	src  = ^dest
//
// For message 6 (Alice to Charlie) the two IDs are swapped by the caller.
func NonceConnectionIDs(nonce uint32) (dest, src uint64) {
	dest = (uint64(nonce) << 32) | uint64(nonce)
	src = ^dest
	return dest, src
}
