// errNoTokenPresent is a sentinel error returned by validateSessionRequestToken
// when the SessionRequest does not contain a NewToken block. This is used by
// handleNewSession to decide whether to send a Retry message.
var errNoTokenPresent = errors.New("no token present in SessionRequest")

// sendRetry constructs and transmits a Retry message to the remote address.
// This is called when config.RequireRetry is enabled and the SessionRequest
// does not carry a valid token. The Retry message contains a fresh token that
// the initiator can include in its next Session Request.
//
// Wire format per ssu2.rst §"Retry (Type 9)" and §"KDF for Retry":
//
//	k          = bik (Bob's intro key)
//	n          = 4-byte packet number from the header
//	ad         = 32-byte header, BEFORE header encryption
//	ciphertext = ENCRYPT(k, n, payload, ad)
//	k_header_1 = bik
//	k_header_2 = bik
//
// so the payload is ChaCha20-Poly1305 sealed and the header is obfuscated —
// a Retry is never transmitted in the clear. The token itself travels in
// header bytes 24-31, not in a payload block.
//
// Payload blocks per spec: DateTime, Address, and optionally Options /
// Termination / Padding. A New Token block is NOT allowed here; the token is a
// header field.
//
// Anti-amplification: the outbound Retry is capped at 3x the incoming message
// size, per ssu2.rst §"Notes" for Retry.
//
// Parameters:
//   - remoteAddr: destination address for the Retry packet
//   - token: 8-byte token to place in header bytes 24-31
//   - originalHeader: header of the SessionRequest (for connection IDs)
//   - incomingSize: size of the message being answered (amplification limit)
//
// terminationReason, when non-nil, adds a Termination block to the Retry payload,
// turning the Retry into a "Don't Retry" message.
//
// Spec ref: ssu2.md §"Session Request" -> §"Notes": "Reject by sending a Retry message
// containing a zero token and a termination block."
func (l *SSU2Listener) sendRetry(remoteAddr *net.UDPAddr, token, originalHeader []byte, incomingSize int, terminationReason *TerminationReason) error {
	if len(token) != TokenSize {
		return oops.Errorf("token must be exactly %d bytes, got %d", TokenSize, len(token))
	}

	cfg := l.config.Load()
	if cfg == nil || len(cfg.IntroKey) != HeaderKeySize {
		// Without the intro key the Retry cannot be AEAD-sealed or header
		// protected as the spec requires, so it must not be sent at all:
		// a plaintext Retry is unreadable by conformant peers and is exactly
		// the fingerprint the spec's header encryption exists to avoid.
		flog("sendRetry", logger.Fields{"remote": remoteAddr.String()}).
			Warn("IntroKey not configured: cannot send spec-compliant Retry (payload AEAD and header protection require it); dropping")
		return oops.
			Code("RETRY_INTRO_KEY_MISSING").
			In("ssu2").
			Errorf("Retry requires a 32-byte IntroKey for AEAD and header protection")
	}

	// Retry carries a random packet number which doubles as the AEAD nonce.
	// ssu2.rst §"Retry": "Packet Number :: Random number generated by Bob".
	packetNumber, err := cryptorand.RandInRange(1, int64(MaxPacketNumber))
	if err != nil {
		return oops.Wrapf(err, "failed to generate Retry packet number")
	}

	header, err := l.buildRetryHeader(originalHeader, token, uint32(packetNumber))
	if err != nil {
		return oops.Wrapf(err, "failed to build Retry header")
	}

	payload, err := l.buildRetryPayload(remoteAddr, terminationReason)
	if err != nil {
		return oops.Wrapf(err, "failed to build Retry payload")
	}

	ciphertext, mac, err := EncryptIntroKeyAEAD(cfg.IntroKey, header, payload, uint32(packetNumber))
	if err != nil {
		return oops.Wrapf(err, "failed to AEAD-encrypt Retry payload")
	}

	retryPacket := NewSSU2Packet(MessageTypeRetry, uint32(packetNumber))
	retryPacket.Header = header
	retryPacket.Payload = ciphertext
	retryPacket.MAC = mac

	packetData, err := retryPacket.Serialize()
	if err != nil {
		return oops.Wrapf(err, "failed to serialize Retry packet")
	}

	// Header protection last: the AEAD already committed to the cleartext
	// header as associated data, so the header must be obfuscated only after
	// sealing (ssu2.rst §"KDF for Retry": "ad = 32 byte header, before header
	// encryption").
	protector, err := NewHeaderProtectorFromIntroKey(cfg.IntroKey, HeaderTypeRetry)
	if err != nil {
		return oops.Wrapf(err, "failed to build Retry header protector")
	}
	if err := protector.EncryptHeader(packetData); err != nil {
		return oops.Wrapf(err, "failed to apply Retry header protection")
	}

	if incomingSize > 0 && len(packetData) > 3*incomingSize {
		return oops.Errorf("Retry message (%d bytes) exceeds 3x amplification limit of incoming message (%d bytes)", len(packetData), incomingSize)
	}

	if _, err := l.underlying.WriteTo(packetData, remoteAddr); err != nil {
		return oops.Wrapf(err, "failed to send Retry packet")
	}
	return nil
}

// buildRetryPayload creates the DateTime + Address blocks required by
// ssu2.rst §"Retry" ("Payload: DateTime block / Address block / Options block
// (optional) / Termination block (optional) / Padding block (optional)").
//
// The Address block reports the peer's own observed address, which is what
// makes it useful for passive NAT detection, as in SessionCreated.
func (l *SSU2Listener) buildRetryPayload(remoteAddr *net.UDPAddr, terminationReason *TerminationReason) ([]byte, error) {
	now := time.Now()

	dateTimeData := make([]byte, 4)
	binary.BigEndian.PutUint32(dateTimeData, uint32(now.Unix()))
	dateTimeBlock := NewSSU2Block(BlockTypeDateTime, dateTimeData)

	ip := remoteAddr.IP
	if ip == nil {
		ip = net.IPv4zero
	}
	port := uint16(remoteAddr.Port)
	addressBlock := EncodeAddressBlock(ip, port)

	blocks := []*SSU2Block{dateTimeBlock, addressBlock}

	// A Termination block, when requested, makes this Retry a "Don't Retry".
	// Spec ref: ssu2.md §"Termination" - "This must be the last non-padding block in the
	// payload", and §"Session Request" -> §"Notes" for the replay-rejection Retry.
	if terminationReason != nil {
		// "valid data packets received :: ... 0 if error occurs in handshake phase"
		termData := make([]byte, 9)
		// bytes 0-7 stay zero: no valid data packets were received.
		termData[8] = byte(*terminationReason)
		blocks = append(blocks, NewSSU2Block(BlockTypeTermination, termData))
	}

	payload, err := SerializeBlocks(blocks)
	if err != nil {
		return nil, oops.Wrapf(err, "failed to serialize Retry payload blocks")
	}
	return payload, nil
}

// buildRetryHeader constructs the 32-byte cleartext long header for a Retry
// message, including the token in bytes 24-31.
//
// ssu2.md §"Retry" -> header table: "Destination Connection ID :: The Source
// Connection ID received from Alice in Token Request or Session Request" and
// "Source Connection ID :: The Destination Connection ID received from Alice".
// Java (PacketBuilder2.buildRetryPacket: dest = state.getSendConnID() = SR
// source, src = state.getRcvConnID() = SR dest) and i2pd both echo Alice's two
// IDs back swapped; a conformant initiator verifies the source half equals its own
// Session Request destination, so it must not be an unrelated stable value.
func (l *SSU2Listener) buildRetryHeader(originalHeader, token []byte, packetNumber uint32) ([]byte, error) {
	header := make([]byte, LongHeaderSize)

	if len(originalHeader) >= 24 {
		// Retry dest = Alice's source conn ID (SR bytes 16-23).
		copy(header[0:8], originalHeader[16:24])
		// Retry source = Alice's destination conn ID (SR bytes 0-7).
		copy(header[16:24], originalHeader[0:8])
	} else if len(originalHeader) >= 8 {
		copy(header[0:8], originalHeader[0:8])
	}

	// bytes 8-11: packet number (also the AEAD nonce)
	header[8] = byte(packetNumber >> 24)
	header[9] = byte(packetNumber >> 16)
	header[10] = byte(packetNumber >> 8)
	header[11] = byte(packetNumber)

	header[12] = MessageTypeRetry
	header[13] = SSU2ProtocolVersion
	header[14] = SSU2NetworkID

	// bytes 24-31: the token Alice must echo in her next Session Request
	copy(header[24:32], token)

	return header, nil
}
