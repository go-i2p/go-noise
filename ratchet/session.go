package ratchet

import (
	"sync"
	"time"

	"github.com/go-i2p/crypto/ratchet"
	"github.com/go-i2p/logger"
	"github.com/samber/oops"
)

// Session represents an active encrypted session with a remote destination.
//
// A session is the long-lived, encrypted conversation between two I2P
// destinations. It maintains separate sending and receiving ratchet chains
// as required by the ECIES-X25519-AEAD-Ratchet protocol.
//
// Thread safety: Session has its own mutex that protects ratchet state
// during crypto operations. The session manager lock and session lock have a
// defined ordering to prevent deadlocks.
//
// See [I2P Spec: ECIES](https://github.com/i2p/i2p.www/blob/master/i2p2www/spec/ecies.rst) for details.
type Session struct {
	mu              sync.Mutex
	RemotePublicKey [32]byte
	DHRatchet       *ratchet.DHRatchet
	// sendRootKey and recvRootKey are the per-direction "next root key"
	// values maintained by the DH Ratchet KDF. The spec keeps an independent
	// nextRootKey for the inbound and outbound directions (ecies.rst
	// §"DH Ratchet KDF": "rootKey = nextRootKey // from previous tagset in
	// this direction"). Before each PerformRatchet call the Session selects
	// the appropriate direction's root key via DHRatchet.SetRootKey and
	// stores the returned nextRootKey back here.
	sendRootKey      [32]byte
	recvRootKey      [32]byte
	SymmetricRatchet *ratchet.SymmetricRatchet // sending chain
	TagRatchet       *ratchet.TagRatchet       // sending tags
	// RecvSymmetricRatchet is the receiving chain ratchet.
	RecvSymmetricRatchet *ratchet.SymmetricRatchet
	// RecvTagRatchet is the receiving tag ratchet.
	RecvTagRatchet *ratchet.TagRatchet
	LastUsed       time.Time
	// Established records when the session was first created.
	// Used for the "replace session if NS received after N minutes" rule.
	// Spec ref: ecies.md §"Parameters" — "Replace session if NS received after: 3 minutes".
	Established    time.Time
	MessageCounter uint32
	// recvWindowBase is the lowest ES message counter we will still accept.
	// It advances as leading counters are consumed.
	// Spec ref: ecies.rst §"Existing Session" — ≤128-message receive window.
	recvWindowBase uint32
	// recvFillMark is the next counter for which we have NOT yet pre-derived a
	// message key.  Keys for [recvWindowBase, recvFillMark) live in recvKeyCache.
	recvFillMark uint32
	// recvKeyCache maps ES message counter → pre-derived message key.
	// Keys are removed from the cache once consumed; the absence of a counter
	// that is within [recvWindowBase, recvFillMark) means it was already used.
	recvKeyCache map[uint32][32]byte
	// pendingTags tracks tags we expect to receive (tag window).
	pendingTags [][8]byte
	// usedTags tracks the number of tags consumed in the current tagset.
	// Used to compute the dynamic target tag window size.
	usedTags uint32
	// dhRatchetCounter tracks messages since last DH ratchet rotation.
	dhRatchetCounter uint32
	// consecutiveDHFailures tracks how many DH ratchet steps have failed in a row.
	consecutiveDHFailures uint32
	// newEphemeralPub holds the new ephemeral public key for the peer.
	newEphemeralPub *[32]byte
	// handshakeState retains intermediate Noise IK state for NSR.
	// Non-nil when NSR has not yet been sent (responder) or received (initiator).
	handshakeState *noiseHandshakeState
	// isInitiator tracks whether we initiated the session (sent NS).
	isInitiator bool
	// nsrTag is the NSR tag registered in the SessionManager's nsrTagIndex.
	// Non-nil only on initiator sessions until the NSR has been received.
	// Used to clean up the index entry on session eviction or expiry.
	nsrTag *[8]byte

	// sendKeyID is the current send-direction DH ratchet key ID.
	// Incremented each time we generate a new forward key.
	// Spec ref: ecies.rst §"Key and Tag Set IDs".
	sendKeyID uint16
	// recvKeyID is the current receive-direction DH ratchet key ID.
	// Updated when we receive a NextKey block from the peer.
	recvKeyID uint16
	// pendingNextKeys holds NextKey blocks to include in the next outgoing message.
	// These are generated when the DH ratchet rotates and consumed when sent.
	pendingNextKeys []PayloadBlock
	// awaitingReverseKey tracks whether we sent a forward NextKey with
	// request-reverse set and are waiting for the peer's reverse key.
	awaitingReverseKey bool
	// nextRecvTagCounter is the ES message counter that the NEXT recv tag
	// generated by RecvTagRatchet.GenerateNextTag() corresponds to.
	// Tags and message keys advance in lockstep: tag N decrypts with
	// the message key at counter N. Tracking this lets us store a
	// tag→counter mapping in SessionManager.tagCounterIndex for O(1)
	// AEAD decryption instead of scanning the entire recv window.
	nextRecvTagCounter uint32

	// pendingAcks holds Ack blocks to include in the next outgoing ES message.
	// These are queued when an AckRequest block is received from the peer.
	// Spec ref: ecies.rst §"Ack" and §"Ack Request".
	pendingAcks []PayloadBlock
	// lastAckedEntries records the most recently received Ack entries from the peer.
	// Callers can inspect this to confirm message delivery.
	lastAckedEntries []AckEntry

	// awaitingFirstES is set to true on the responder (Bob) after sending an NSR.
	// The spec (ecies.rst §"Notes" after §1g) states:
	//   "Bob must receive an ES message from Alice before sending ES messages."
	// While this flag is true, encryptExistingSession will reject outbound ES.
	// It is cleared when the first inbound ES message is successfully decrypted.
	awaitingFirstES bool
}

// createSession initializes a new Session with ratchet state from derived keys.
// The isInitiator flag determines key direction: the initiator sends on k_ab
// and receives on k_ba; the responder sends on k_ba and receives on k_ab.
//
// Spec ref: ecies.rst §"Data Phase" — after split() produces k_ab and k_ba,
// each direction gets its own DH_INITIALIZE + TagAndKeyGenKeys:
//
//	tagset_ab = DH_INITIALIZE(chainKey, k_ab)
//	tagset_ba = DH_INITIALIZE(chainKey, k_ba)
func createSession(remotePubKey [32]byte, keys *sessionKeys, ourPrivateKey [32]byte, isInitiator bool) (*Session, error) {
	flog("createSession", logger.Fields{"is_initiator": isInitiator}).Debug("Creating new ratchet session")

	// Select directional keys based on role.
	var sendK, recvK [32]byte
	if isInitiator {
		sendK = keys.kAB // initiator → responder
		recvK = keys.kBA // responder → initiator
	} else {
		sendK = keys.kBA // responder → initiator
		recvK = keys.kAB // initiator → responder
	}

	// Derive per-direction tag sets (DH_INITIALIZE + TagAndKeyGenKeys).
	sendRootKey, sendTagCK, sendSymCK, err := deriveDirectionalTagSet(keys.chainKey, sendK)
	if err != nil {
		return nil, oops.Wrapf(err, "failed to derive send-direction tag set")
	}
	// The recv-direction nextRootKey is the KDF input for the first DH ratchet
	// step in the receive direction. The spec maintains an independent
	// nextRootKey per direction (ecies.rst §"DH Ratchet KDF"), so both are
	// stored on the Session.
	recvRootKey, recvTagCK, recvSymCK, err := deriveDirectionalTagSet(keys.chainKey, recvK)
	if err != nil {
		return nil, oops.Wrapf(err, "failed to derive recv-direction tag set")
	}

	// The DHRatchet's rootKey is a working value the Session selects per
	// direction via SetRootKey before each ratchet step. Initialize it with
	// the send-direction root key (the send direction ratchets first).
	dhRatchet := ratchet.NewDHRatchet(sendRootKey, ourPrivateKey, remotePubKey)
	symRatchet := ratchet.NewSymmetricRatchet(sendSymCK)
	tagRatchet := ratchet.NewTagRatchet(sendTagCK)
	recvSymRatchet := ratchet.NewSymmetricRatchet(recvSymCK)
	recvTagRatchet := ratchet.NewTagRatchet(recvTagCK)

	return &Session{
		RemotePublicKey:      remotePubKey,
		DHRatchet:            dhRatchet,
		sendRootKey:          sendRootKey,
		recvRootKey:          recvRootKey,
		SymmetricRatchet:     symRatchet,
		TagRatchet:           tagRatchet,
		RecvSymmetricRatchet: recvSymRatchet,
		RecvTagRatchet:       recvTagRatchet,
		LastUsed:             time.Now(),
		Established:          time.Now(),
		// ES message counters are 0-based: the first Existing Session message pairs
		// tag_0 with nonce 0.
		//
		// Spec ref: ecies.rst §"3) AEAD (ChaChaPoly)" → "Existing Session Inputs":
		//   "n :: Counter-based nonce, 12 bytes. Starts at 0 and incremented for each
		//   message... Last eight bytes are the message number (n), little-endian encoded."
		// and §"4) Ratchets" → "Message Numbers": "The receiver looks up the index of
		// the tag, this is the message number N."
		//
		// Both reference implementations agree on counter 0 for the first ES message:
		//   Java I2P RatchetTagSet.java: _lastKey = -1, consumeNextKey() does _lastKey++
		//     and returns SessionKeyAndNonce(key, _id, _lastKey, ...) -> first nonce 0.
		//   i2pd ECIESX25519AEADRatchetSession.cpp: NextSessionTagRatchet() sets
		//     m_NextIndex = 0; NewExistingSessionMessage() reads index = GetNextIndex()
		//     (0), calls CreateNonce(index), and only then GetNextSessionTag() increments.
		//
		// The NS/NSR handshake messages use their own separate "SessionReplyTags"
		// tagset, so they do not consume ES counter 0.
		MessageCounter:       0,
		recvWindowBase:     0,
		recvFillMark:       0,
		recvKeyCache:       make(map[uint32][32]byte),
		pendingTags:        make([][8]byte, 0, tagWindowMin),
		pendingNextKeys:    nil,
		nextRecvTagCounter: 0,
	}, nil
}

// GetPendingAcks returns any Ack blocks that should be included in the next
// outgoing Existing Session message. The returned blocks are removed from the
// session's pending queue.
//
// Spec ref: ecies.rst §"Ack" — after receiving an AckRequest block, the
// recipient should include an Ack block in the next outgoing message.
//
// Must be called with session.mu held.
func (s *Session) GetPendingAcks() []PayloadBlock {
	if len(s.pendingAcks) == 0 {
		return nil
	}
	// Return a copy to avoid aliasing the backing array.
	result := append([]PayloadBlock(nil), s.pendingAcks...)
	s.pendingAcks = nil
	return result
}

// GetLastAckedEntries returns the most recently received Ack entries from the
// peer. This allows callers to confirm which messages the peer has received.
//
// Must be called with session.mu held.
func (s *Session) GetLastAckedEntries() []AckEntry {
	return s.lastAckedEntries
}
